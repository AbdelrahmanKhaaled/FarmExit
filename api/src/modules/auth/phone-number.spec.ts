import { normalizeMobile } from './phone-number';

describe('normalizeMobile', () => {
  it.each([
    ['01012345678', '+201012345678'],
    ['1012345678', '+201012345678'],
    ['+20 101 234 5678', '+201012345678'],
    ['0020-10-1234-5678', '+201012345678'],
    ['201012345678', '+201012345678'],
    ['(010) 1234 5678', '+201012345678'],
    ['٠١٠١٢٣٤٥٦٧٨', '+201012345678'],
    ['01112345678', '+201112345678'],
    ['01212345678', '+201212345678'],
    ['01512345678', '+201512345678'],
    ['+14155552671', '+14155552671'],
    ['00442071838750', '+442071838750'],
  ])('normalises %s', (input, expected) => {
    expect(normalizeMobile(input)).toBe(expected);
  });

  it.each(['', 'abc', '0101234567', '010123456789', '01312345678', '+2001012345678', '+0123456789', '+1234', '12-34'])(
    'rejects %p',
    (input) => {
      expect(normalizeMobile(input)).toBeNull();
    },
  );
});
