import { hasLocale } from 'next-intl';
import { setRequestLocale } from 'next-intl/server';
import { notFound } from 'next/navigation';
import { routing } from '@/i18n/routing';
import { requireCompletedProfile } from '@/lib/auth/require-session';
import { ProfileContent } from '@/features/my-farmexit/ProfileContent';
export default async function MyProfilePage({ params }: PageProps<'/[locale]/my/profile'>) {
  const { locale } = await params;
  if (!hasLocale(routing.locales, locale)) notFound();
  setRequestLocale(locale);
  const session = await requireCompletedProfile(locale, `/${locale}/my/profile`);
  return <ProfileContent user={session.user} />;
}
